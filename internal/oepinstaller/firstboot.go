package oepinstaller

import (
	_ "embed"
	"fmt"
	"net/url"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"

	"github.com/open-edge-platform/image-composer-tool/internal/config"
)

// In-image paths of the first-boot installation.
const (
	cliDir          = "/usr/local/share/oep-installer"
	firstBootScript = "/usr/local/sbin/ict-oep-installer.sh"
	firstBootName   = "oep-installer"
	sudoersInclude  = "/etc/sudoers.d/90-ict-oep-installer"
	grantDir        = "/run/ict-oep-installer.d"
	tmpfilesConf    = "/etc/tmpfiles.d/ict-oep-installer.conf"
	userEnv, cliEnv = "OEP_INSTALLER_USER", "OEP_INSTALLER_CLI"
	sudoPackage     = "sudo"
	includeContents = "# Generated by image-composer-tool: the OEP Installer's temporary sudo grant is written to\n" +
		"# this directory in /run while its first-boot script runs, so a reboot always removes it.\n" +
		"#includedir " + grantDir + "\n"
	// tmpfilesContents has systemd create the grant directory at every boot. The
	// sudoers include above stays in the image for good, and sudo-rs, the sudo
	// of Ubuntu 26.04, reports a missing included directory as a sudoers error on
	// every sudo command (users with a rule elsewhere can still use sudo). /run is
	// empty after each boot, so without this the directory exists only once the
	// first-boot script has run in the current boot.
	tmpfilesContents = "# Generated by image-composer-tool: keeps the sudoers include of the OEP Installer's\n" +
		"# temporary sudo grant valid at every boot.\n" +
		"d " + grantDir + " 0755 root root -\n"
	// recoveryFormat is shown at the login prompt when the first-boot script
	// fails, with the user that runs openedge-cli.
	recoveryFormat = "as %s run ~/.local/bin/openedge-cli resume"
)

// cliFileNameRe limits the CLI's in-image file name, taken from its URL.
var cliFileNameRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$`)

//go:embed firstboot.sh
var firstBootScriptContents []byte

// AddFirstBoot copies cli, the OEP Installer the template names, into the
// image and adds a first-boot provisioning script, ordered after the
// template's scripts, that runs its setup command and then
// "openedge-cli install" for the template's modules and arguments as the
// template's user, with passwordless sudo only while it runs. If it fails it
// is not run again at boot: the user is told at login to fix the problem and
// resume the installation by hand. workDir holds the generated files until the
// image is built.
func AddFirstBoot(t *config.ImageTemplate, cli []byte, workDir string) error {
	o := t.SystemConfig.OEPInstaller
	cliFinal, err := cliPath(o.URL)
	if err != nil {
		return err
	}
	// ICT copies generated files into the image from absolute paths; the
	// configured temp directory is relative to the working directory.
	absDir, err := filepath.Abs(workDir)
	if err != nil {
		return fmt.Errorf("resolving %s: %w", workDir, err)
	}
	// The sudoers entry is mode 0440, as sudo and visudo expect; the copy into
	// the image keeps the mode.
	files := []struct {
		name, final string
		data        []byte
		mode        os.FileMode
	}{
		{"openedge-cli", cliFinal, cli, 0o644},
		{"ict-oep-installer.sh", firstBootScript, firstBootScriptContents, 0o644},
		{"ict-oep-installer.sudoers", sudoersInclude, []byte(includeContents), 0o440},
		{"ict-oep-installer.tmpfiles", tmpfilesConf, []byte(tmpfilesContents), 0o644},
	}
	locals := make([]string, len(files))
	for i, f := range files {
		locals[i] = filepath.Join(absDir, f.name)
		if err := os.WriteFile(locals[i], f.data, f.mode); err != nil {
			return fmt.Errorf("writing %s: %w", f.name, err)
		}
	}
	if err := t.AddGeneratedFile(locals[0], cliFinal); err != nil {
		return err
	}
	if err := t.AddGeneratedFile(locals[2], sudoersInclude); err != nil {
		return err
	}
	if err := t.AddGeneratedFile(locals[3], tmpfilesConf); err != nil {
		return err
	}
	if !slices.Contains(t.SystemConfig.Packages, sudoPackage) {
		t.SystemConfig.Packages = append(t.SystemConfig.Packages, sudoPackage)
	}
	script := config.ProvisioningScript{
		Name:  firstBootName,
		Local: locals[1],
		Final: firstBootScript,
		Order: nextScriptOrder(t.SystemConfig.Provisioning.Scripts),
		Args:  append(slices.Clone(o.Modules), o.Args...),
		Env:   map[string]string{userEnv: o.User, cliEnv: cliFinal},
	}
	// A failed run leaves a half-finished installation; running it again
	// unattended at every boot hides the failure instead of fixing it. An img
	// image keeps no state across boots, so there the script always runs again
	// and the failure notice says so.
	if t.Target.ImageType != config.ImageTypeInitrd {
		script.StopOnFailure = true
		script.RecoveryHint = fmt.Sprintf(recoveryFormat, o.User)
	}
	return t.AddGeneratedProvisioningScript(script)
}

// cliPath returns the in-image path of the CLI, named after the file at rawURL.
func cliPath(rawURL string) (string, error) {
	u, err := url.Parse(rawURL)
	if err != nil {
		return "", fmt.Errorf("invalid systemConfig.oepInstaller.url %q: %w", rawURL, err)
	}
	name := path.Base(u.Path)
	if !cliFileNameRe.MatchString(name) {
		return "", fmt.Errorf("systemConfig.oepInstaller.url %q does not end in a file name", rawURL)
	}
	return path.Join(cliDir, name), nil
}

// nextScriptOrder returns an order that runs after every script in scripts.
func nextScriptOrder(scripts []config.ProvisioningScript) int {
	order := 0
	for _, s := range scripts {
		order = max(order, s.Order+1)
	}
	return order
}
