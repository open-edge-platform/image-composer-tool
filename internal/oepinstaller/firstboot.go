package oepinstaller

import (
	_ "embed"
	"fmt"
	"net/url"
	"os"
	"path"
	"path/filepath"
	"regexp"
	"slices"

	"github.com/open-edge-platform/image-composer-tool/internal/config"
)

// In-image paths of the first-boot installation.
const (
	cliDir           = "/usr/local/share/oep-installer"
	firstBootScript  = "/usr/local/sbin/ict-oep-installer.sh"
	firstBootName    = "oep-installer"
	sudoersFile      = "/etc/sudoers.d/90-ict-oep-installer"
	sudoersTmpfiles  = "/usr/lib/tmpfiles.d/ict-oep-installer.conf"
	userEnv, cliEnv  = "OEP_INSTALLER_USER", "OEP_INSTALLER_CLI"
	sudoPackage      = "sudo"
	tmpfilesContents = "# Generated by image-composer-tool: remove the OEP Installer's temporary sudo grant at boot.\n" +
		"r " + sudoersFile + "\n"
)

// cliFileNameRe limits the CLI's in-image file name, taken from its URL.
var cliFileNameRe = regexp.MustCompile(`^[A-Za-z0-9][A-Za-z0-9._-]{0,127}$`)

//go:embed firstboot.sh
var firstBootScriptContents []byte

// AddFirstBoot copies cli, the OEP Installer the template names, into the
// image and adds a first-boot provisioning script, ordered after the
// template's scripts, that runs its setup command and then
// "openedge-cli install" for the template's modules and arguments as the
// template's user, with passwordless sudo only while it runs. workDir holds
// the generated files until the image is built.
func AddFirstBoot(t *config.ImageTemplate, cli []byte, workDir string) error {
	o := t.SystemConfig.OEPInstaller
	cliFinal, err := cliPath(o.URL)
	if err != nil {
		return err
	}
	files := []struct {
		name, final string
		data        []byte
	}{
		{"openedge-cli", cliFinal, cli},
		{"ict-oep-installer.sh", firstBootScript, firstBootScriptContents},
		{"ict-oep-installer.conf", sudoersTmpfiles, []byte(tmpfilesContents)},
	}
	locals := make([]string, len(files))
	for i, f := range files {
		locals[i] = filepath.Join(workDir, f.name)
		if err := os.WriteFile(locals[i], f.data, 0o644); err != nil {
			return fmt.Errorf("writing %s: %w", f.name, err)
		}
	}
	if err := t.AddGeneratedFile(locals[0], cliFinal); err != nil {
		return err
	}
	if err := t.AddGeneratedFile(locals[2], sudoersTmpfiles); err != nil {
		return err
	}
	if !slices.Contains(t.SystemConfig.Packages, sudoPackage) {
		t.SystemConfig.Packages = append(t.SystemConfig.Packages, sudoPackage)
	}
	return t.AddGeneratedProvisioningScript(config.ProvisioningScript{
		Name:  firstBootName,
		Local: locals[1],
		Final: firstBootScript,
		Order: nextScriptOrder(t.SystemConfig.Provisioning.Scripts),
		Args:  append(slices.Clone(o.Modules), o.Args...),
		Env:   map[string]string{userEnv: o.User, cliEnv: cliFinal},
	})
}

// cliPath returns the in-image path of the CLI, named after the file at rawURL.
func cliPath(rawURL string) (string, error) {
	u, err := url.Parse(rawURL)
	if err != nil {
		return "", fmt.Errorf("invalid systemConfig.oepInstaller.url %q: %w", rawURL, err)
	}
	name := path.Base(u.Path)
	if !cliFileNameRe.MatchString(name) {
		return "", fmt.Errorf("systemConfig.oepInstaller.url %q does not end in a file name", rawURL)
	}
	return path.Join(cliDir, name), nil
}

// nextScriptOrder returns an order that runs after every script in scripts.
func nextScriptOrder(scripts []config.ProvisioningScript) int {
	order := 0
	for _, s := range scripts {
		order = max(order, s.Order+1)
	}
	return order
}
